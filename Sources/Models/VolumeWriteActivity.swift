import Foundation

/// 一块卷「正在被写入」的实测证据。
///
/// ## 为什么需要它（用户报的症）
///
/// 2026-10-30 用户在访达里往两块外置盘拷数据，应用却显示「可安全推出」。
/// 实测：拷贝期间 `影视盘` 可用空间 5 秒内减少约 168 MB（≈ 33 MB/s），
/// 而 `lsof` 对两块卷 **0 命中** —— 访达的拷贝走的是不需要「完全磁盘访问」的路径，
/// 非 root 进程看不到它持有哪些文件。
///
/// ⇒ 结论是：**「谁在占用」与「有没有在写」是两条互不覆盖的证据线**。
/// `lsof` 能回答「谁开着文件」（可靠的、可点名的），但对访达拷贝完全失明；
/// 而可用空间的变化不需要任何权限，虽然**说不出是谁**，却能确定「正在写」。
///
/// 本类型就是后一条线的产物。它**不是** ``OccupyingProcess`` 的替代品：
/// 没有 pid、没有可终止的对象，所以它不会进入 ``OccupancyResult``，
/// 也就不会被「关闭并推出」拿去清场（那会把一个不存在的 pid 发给 `kill`）。
struct VolumeWriteActivity: Equatable, Sendable {

    /// 本轮测得的写入速率（字节/秒），恒为正（可用空间变小才算写入）。
    let bytesPerSecond: Int64

    /// 速率对应的时间点（后一次采样时刻）。
    ///
    /// 保留时间是为了让界面能判断这份证据是否「还新鲜」——
    /// 轮询停掉时界面不应永远挂着「正在写入」。
    let sampledAt: Date

    /// 供文案插值的速率，如 `36 MB/s`。
    ///
    /// 「/s」是速率单位的一部分，**不随语言变化**（与 ``ByteFormat`` 的 1000 进制同一口径），
    /// 所以留在代码里而不是本地化模板里；本地化的只是「约 %@/秒」这种句式。
    var formattedRate: String { "\(ByteFormat.string(bytesPerSecond))/s" }
}
